// Package gonotices writes the licence notices of the Go modules compiled
// into impr: third-party-notices-go.md at the repository root, beside the
// web UI's third-party-notices.md, which the Tabler tool owns and rewrites
// whole. Keeping the two in separate files lets each generator rewrite its
// own file deterministically without reading the other's.
package gonotices

import (
	"bufio"
	"errors"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// File is the notices file, relative to the repository root.
const File = "third-party-notices-go.md"

// Module is one module compiled into the program, with the folder that holds
// its source (the module cache, or GOROOT for the standard library).
type Module struct {
	Path, Version, Dir string
}

// Notice is a module with its licence files, read in full.
type Notice struct {
	Module
	Files []LicenceFile
}

// LicenceFile is one licence or notice file at a module's root.
type LicenceFile struct {
	Name, Text string
}

var licenceName = regexp.MustCompile(`(?i)^(licen[cs]e|copying|notice|patents)(\.(md|txt))?$`)

// ListFormat is the `go list -deps -f` template whose output Parse reads:
// one line per package in a module other than the main one.
const ListFormat = `{{if .Module}}{{if not .Module.Main}}{{.Module.Path}}{{"\t"}}{{.Module.Version}}{{"\t"}}{{.Module.Dir}}{{end}}{{end}}`

// Parse reads `go list -deps -f ListFormat ./cmd/impr` output and returns its
// modules once each, sorted by path, after the standard library (from
// goroot). The listing comes in on stdin from the Makefile, since impr's
// code runs no program but through internal/execx, which allows only go
// build.
func Parse(r io.Reader, goroot string) ([]Module, error) {
	if goroot == "" {
		return nil, errors.New("no GOROOT given")
	}
	seen := map[string]Module{}
	sc := bufio.NewScanner(r)
	for sc.Scan() {
		if strings.TrimSpace(sc.Text()) == "" {
			continue
		}
		f := strings.Split(sc.Text(), "\t")
		if len(f) != 3 || f[0] == "" || f[1] == "" || f[2] == "" {
			return nil, fmt.Errorf("go list line %q: want path, version and folder (a replace directive, or a module not downloaded)", sc.Text())
		}
		seen[f[0]] = Module{Path: f[0], Version: f[1], Dir: f[2]}
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	mods := make([]Module, 0, len(seen))
	for _, m := range seen {
		mods = append(mods, m)
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].Path < mods[j].Path })
	return append([]Module{{Path: "Go standard library and runtime", Dir: goroot}}, mods...), nil
}

// Read reads each module's licence files from its root, sorted by name. A
// module with none is an error: its notice cannot be shipped.
func Read(mods []Module) ([]Notice, error) {
	var out []Notice
	for _, m := range mods {
		ents, err := os.ReadDir(m.Dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.Path, err)
		}
		n := Notice{Module: m}
		for _, e := range ents {
			if e.IsDir() || !licenceName.MatchString(e.Name()) {
				continue
			}
			b, err := os.ReadFile(filepath.Join(m.Dir, e.Name())) //nolint:gosec // G304: a licence file in the module cache or GOROOT
			if err != nil {
				return nil, fmt.Errorf("%s: %w", m.Path, err)
			}
			n.Files = append(n.Files, LicenceFile{Name: e.Name(), Text: string(b)})
		}
		if len(n.Files) == 0 {
			return nil, fmt.Errorf("%s %s has no licence file at its root (%s)", m.Path, m.Version, m.Dir)
		}
		sort.Slice(n.Files, func(i, j int) bool { return n.Files[i].Name < n.Files[j].Name })
		out = append(out, n)
	}
	return out, nil
}

// Render writes the notices file. The same notices always give the same
// bytes: the order is fixed, and nothing about the host (paths, dates) is
// written.
func Render(ns []Notice) []byte {
	var b strings.Builder
	b.WriteString("# Third-party notices: Go modules\n\n")
	fmt.Fprintf(&b, "Every impr binary compiles in the Go standard library and the %d Go modules below.\n", len(ns)-1)
	b.WriteString("Each licence and notice file follows in full, as each module ships it.\n")
	b.WriteString("The web UI's embedded assets are listed in third-party-notices.md.\n")
	b.WriteString("This file is generated by `make notices` (`go list -deps ./cmd/impr` over the module cache);\n")
	b.WriteString("do not edit it by hand. `scripts/test-all.sh` fails when it is out of date.\n")
	for _, n := range ns {
		b.WriteString("\n## " + n.Path)
		if n.Version != "" {
			b.WriteString(" " + n.Version)
		}
		b.WriteString("\n")
		for _, f := range n.Files {
			text := strings.ReplaceAll(f.Text, "\r\n", "\n")
			fence := "```"
			for strings.Contains(text, fence) {
				fence += "`"
			}
			fmt.Fprintf(&b, "\n%s:\n\n%stext\n%s\n%s\n", f.Name, fence, strings.TrimRight(text, "\n"), fence)
		}
	}
	return []byte(b.String())
}

// ErrStale is Check's error when the file differs from what Render makes.
var ErrStale = errors.New(File + " is out of date")
