// noDailyCheck are the commands that never trigger the daily expiry check:
// what sange calls on every run (companion, profile, cert), the long-running
// server (which checks on its own ticker), and commands about notifications
// or expiry themselves.
var noDailyCheck = map[string]bool{"companion": true, "cert": true, "serve": true, "notify": true, "completion": true, "help": true}

// dailyExpiryCheck runs `impr cert list` at most once a day after another
// command, when notify.checkOnCommand is on, so certificates near expiry are
// raised on a machine that runs neither impr serve nor a scheduled check.
// It never changes the command's exit code or output.
func (a *App) dailyExpiryCheck(ctx context.Context, cmd string) {
	if noDailyCheck[cmd] {
		return
	}
	d, err := a.dirs()
	if err != nil {
		return
	}
	eff, err := a.effective(d)
	if err != nil || !eff.Config.Notify.CheckOnCommand {
		return
	}
	stamp := filepath.Join(d.State, "notify", "last-expiry-check")
	if b, err := os.ReadFile(stamp); err == nil { //nolint:gosec // G304: impr's own state file
		if t, err := time.Parse(time.RFC3339, strings.TrimSpace(string(b))); err == nil && a.Now().Sub(t) < 24*time.Hour {
			return
		}
	}
	if err := os.MkdirAll(filepath.Dir(stamp), 0o700); err != nil {
		return
	}
	if err := os.WriteFile(stamp, []byte(a.Now().UTC().Format(time.RFC3339)+"\n"), 0o600); err != nil {
		return
	}
	a.runCaptured(ctx, []string{"cert", "list", "--json"})
}

var certCheckFlags = flagSpec{"print": boolFlag, "for": stringFlag, "exe": stringFlag}

// cmdCertInstallCheck prints a daily scheduled `impr cert list` for this
// user, and how to install it. Like impr serve install-unit, it never
// installs anything itself.
func cmdCertInstallCheck(_ context.Context, a *App, args []string) (int, error) {
	p, err := parse(args, certCheckFlags)
	if err != nil {
		return 0, err
	}
	if !p.on("print") {
		return 0, contract.New(contract.Usage, "impr never installs a scheduled task; --print shows it and how to install it").
			WithFix("impr cert install-check --print")
	}
	kind := p.str("for")
	if kind == "" {
		kind = map[string]string{"darwin": "launchd", "windows": "task"}[a.GOOS]
		if kind == "" {
			kind = "systemd"
		}
	}
	exe, err := unitExe(p.str("exe"))
	if err != nil {
		return 0, err
	}
	d, err := a.dirs()
	if err != nil {
		return 0, contract.Wrap(contract.Unavailable, err, "locate the imprimatur config")
	}
	u := Unit{Exe: exe, Config: d.Config, State: d.State}
	switch kind {
	case "systemd":
		_, _ = fmt.Fprint(a.Stdout, SystemdCheck(u))
		a.say("unit      save the two parts as ~/.config/systemd/user/impr-cert-check.service and .timer, then:")
		a.say("unit      systemctl --user daemon-reload && systemctl --user enable --now impr-cert-check.timer")
	case "launchd":
		_, _ = fmt.Fprint(a.Stdout, LaunchdCheck(u))
		a.say("unit      save it as ~/Library/LaunchAgents/%s.plist, then: launchctl bootstrap gui/$(id -u) ~/Library/LaunchAgents/%s.plist", checkLabel, checkLabel)
	case "task":
		_, _ = fmt.Fprint(a.Stdout, TaskCheckXML(u))
		a.say(`unit      save it as impr-cert-check.xml, then: schtasks /Create /TN "imprimatur\impr cert check" /XML impr-cert-check.xml`)
	default:
		return 0, contract.New(contract.Usage, "--for is systemd, launchd or task")
	}
	a.say("unit      impr installed nothing")
	return 0, nil
}

const checkLabel = "sh.sange.imprimatur.cert-check"

// SystemdCheck is a oneshot service and a daily timer, sandboxed to write
// only impr's state directory.
func SystemdCheck(u Unit) string {
	return `# impr cert list once a day: two units. Generated by impr cert install-check --print.
# ---- impr-cert-check.service ----
[Unit]
Description=imprimatur certificate expiry check (impr cert list)

[Service]
Type=oneshot
ExecStart=` + systemdQuote(u.Exe) + ` cert list
UMask=0077
NoNewPrivileges=yes
PrivateTmp=yes
ProtectSystem=strict
ProtectHome=read-only
ReadWritePaths=` + systemdQuote(u.State) + `
# ---- impr-cert-check.timer ----
[Unit]
Description=Run impr cert list daily

[Timer]
OnCalendar=daily
Persistent=true
RandomizedDelaySec=1h

[Install]
WantedBy=timers.target
`
}

// LaunchdCheck runs impr cert list once a day, at 09:00.
func LaunchdCheck(u Unit) string {
	return `<?xml version="1.0" encoding="UTF-8"?>
<!-- impr cert list once a day, generated by impr cert install-check. -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>` + checkLabel + `</string>
  <key>ProgramArguments</key>
  <array>
    <string>` + xmlText(u.Exe) + `</string>
    <string>cert</string>
    <string>list</string>
  </array>
  <key>StartCalendarInterval</key><dict><key>Hour</key><integer>9</integer><key>Minute</key><integer>0</integer></dict>
  <key>ProcessType</key><string>Background</string>
  <key>Umask</key><integer>63</integer>
</dict>
</plist>
`
}

// TaskCheckXML runs impr cert list daily, and at logon when a day was missed.
func TaskCheckXML(u Unit) string {
	return `<?xml version="1.0" encoding="UTF-8"?>
<!-- impr cert list once a day, generated by impr cert install-check. -->
<Task version="1.4" xmlns="http://schemas.microsoft.com/windows/2004/02/mit/task">
  <RegistrationInfo><Description>imprimatur certificate expiry check (impr cert list)</Description></RegistrationInfo>
  <Triggers><CalendarTrigger><StartBoundary>2026-01-01T09:00:00</StartBoundary><Enabled>true</Enabled><ScheduleByDay><DaysInterval>1</DaysInterval></ScheduleByDay></CalendarTrigger></Triggers>
  <Principals><Principal id="Author"><LogonType>InteractiveToken</LogonType><RunLevel>LeastPrivilege</RunLevel></Principal></Principals>
  <Settings>
    <StartWhenAvailable>true</StartWhenAvailable>
    <MultipleInstancesPolicy>IgnoreNew</MultipleInstancesPolicy>
    <ExecutionTimeLimit>PT10M</ExecutionTimeLimit>
    <Hidden>true</Hidden>
  </Settings>
  <Actions Context="Author">
    <Exec><Command>` + xmlText(u.Exe) + `</Command><Arguments>cert list</Arguments></Exec>
  </Actions>
</Task>
`
}
