// completionModel reads the usage text, the one list of commands and options,
// into command -> the subcommands and options it takes. Completion is
// generated from it, so it cannot drift from what impr accepts.
func completionModel() map[string][]string {
	words := map[string]map[string]bool{}
	cmd := ""
	optRe := regexp.MustCompile(`--[a-z][a-z-]*`)
	subRe := regexp.MustCompile(`^[a-z][a-z-]*$`)
	add := func(w string) {
		if cmd != "" && w != "" {
			words[cmd][w] = true
		}
	}
	for _, line := range strings.Split(usageText, "\n") {
		rest, ok := strings.CutPrefix(line, "  impr ")
		switch {
		case ok:
			f := strings.Fields(rest)
			cmd = f[0]
			if words[cmd] == nil {
				words[cmd] = map[string]bool{}
			}
			// The second word, and the first word after each " | ", name
			// subcommands when they are plain words (a|b|c lists several).
			segments := strings.Split(strings.Join(f[1:], " "), " | ")
			for _, seg := range segments {
				sf := strings.Fields(seg)
				if len(sf) == 0 {
					continue
				}
				for _, s := range strings.Split(sf[0], "|") {
					if subRe.MatchString(s) {
						add(s)
					}
				}
			}
		case strings.HasPrefix(line, "            ") && cmd != "":
			// a continuation of the command above
		default:
			cmd = ""
			continue
		}
		for _, o := range optRe.FindAllString(line, -1) {
			add(o)
		}
	}
	out := map[string][]string{}
	for c, ws := range words {
		list := []string{}
		for w := range ws {
			list = append(list, w)
		}
		sort.Strings(list)
		out[c] = list
	}
	out["help"] = commandNames()
	// An alias completes like the command it stands for: impr s --pro<TAB>.
	for a, full := range aliases {
		out[a] = out[full]
	}
	return out
}

// completionValues reads, from the usage text, the values each command's
// options take where the usage lists them (--purpose release|test|internal,
// --platforms windows,macos,...): command -> option -> values (ID-17).
func completionValues() map[string]map[string][]string {
	valRe := regexp.MustCompile(`(--[a-z][a-z-]*) ([a-z][a-z:]*(?:[|,][a-z][a-z:]*)+)`)
	out := map[string]map[string][]string{}
	cmd := ""
	for _, line := range strings.Split(usageText, "\n") {
		if rest, ok := strings.CutPrefix(line, "  impr "); ok {
			cmd = strings.Fields(rest)[0]
		} else if !strings.HasPrefix(line, "            ") {
			cmd = ""
		}
		if cmd == "" {
			continue
		}
		for _, m := range valRe.FindAllStringSubmatch(line, -1) {
			if out[cmd] == nil {
				out[cmd] = map[string][]string{}
			}
			out[cmd][m[1]] = strings.FieldsFunc(m[2], func(r rune) bool { return r == '|' || r == ',' })
		}
	}
	for a, full := range aliases {
		if out[full] != nil {
			out[a] = out[full]
		}
	}
	return out
}

// valueCases lists "command option" -> values, sorted, for the scripts.
func valueCases() [][2]string {
	var cases [][2]string
	for cmd, opts := range completionValues() {
		for opt, vals := range opts {
			cases = append(cases, [2]string{cmd + " " + opt, strings.Join(vals, " ")})
		}
	}
	sort.Slice(cases, func(i, j int) bool { return cases[i][0] < cases[j][0] })
	return cases
}

// commandNames are the top-level commands, from the dispatch table.
func commandNames() []string {
	names := []string{"help", "version"}
	for n := range commands {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func sortedKeys(m map[string][]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// CompletionScript renders the completion for one shell.
func CompletionScript(shell string) (string, error) {
	m := completionModel()
	cmds := strings.Join(commandNames(), " ")
	var b strings.Builder
	switch shell {
	case "bash":
		b.WriteString("# impr completion for bash (generated by impr completion bash)\n# impr-version: " + version + "\n_impr() {\n  local cur=${COMP_WORDS[COMP_CWORD]} prev=${COMP_WORDS[COMP_CWORD-1]}\n")
		// bash splits --opt=value at the "=" (COMP_WORDBREAKS): the option
		// is then the word before the "=", as the PowerShell line read it (O-95).
		b.WriteString("  if [ \"$cur\" = \"=\" ]; then cur=; elif [ \"$prev\" = \"=\" ]; then prev=${COMP_WORDS[COMP_CWORD-2]}; fi\n")
		fmt.Fprintf(&b, "  if [ \"$COMP_CWORD\" -eq 1 ]; then COMPREPLY=($(compgen -W %q -- \"$cur\")); return; fi\n", cmds)
		b.WriteString("  case \"${COMP_WORDS[1]} $prev\" in\n")
		for _, c := range valueCases() {
			fmt.Fprintf(&b, "    %q) COMPREPLY=($(compgen -W %q -- \"$cur\")); return;;\n", c[0], c[1])
		}
		b.WriteString("  esac\n  case ${COMP_WORDS[1]} in\n")
		for _, c := range sortedKeys(m) {
			fmt.Fprintf(&b, "    %s) COMPREPLY=($(compgen -W %q -- \"$cur\"));;\n", c, strings.Join(m[c], " "))
		}
		b.WriteString("  esac\n}\ncomplete -o default -F _impr impr\n")
	case "zsh":
		b.WriteString("#compdef impr\n# impr completion for zsh (generated by impr completion zsh)\n# impr-version: " + version + "\n_impr() {\n")
		fmt.Fprintf(&b, "  if (( CURRENT == 2 )); then compadd -- %s; return; fi\n", cmds)
		b.WriteString("  case \"$words[2] $words[CURRENT-1]\" in\n")
		for _, c := range valueCases() {
			fmt.Fprintf(&b, "    %q) compadd -- %s; return;;\n", c[0], c[1])
		}
		b.WriteString("  esac\n  case $words[2] in\n")
		for _, c := range sortedKeys(m) {
			fmt.Fprintf(&b, "    %s) compadd -- %s;;\n", c, strings.Join(m[c], " "))
		}
		b.WriteString("  esac\n  _files\n}\n_impr \"$@\"\n")
	case "fish":
		b.WriteString("# impr completion for fish (generated by impr completion fish)\n# impr-version: " + version + "\ncomplete -c impr -f\n")
		fmt.Fprintf(&b, "complete -c impr -n __fish_use_subcommand -a %q\n", cmds)
		for _, c := range sortedKeys(m) {
			fmt.Fprintf(&b, "complete -c impr -n '__fish_seen_subcommand_from %s' -a %q\n", c, strings.Join(m[c], " "))
		}
		for _, c := range valueCases() {
			cmd, opt, _ := strings.Cut(c[0], " ")
			fmt.Fprintf(&b, "complete -c impr -n '__fish_seen_subcommand_from %s' -l %s -xa %q\n", cmd, strings.TrimPrefix(opt, "--"), c[1])
		}
	case "powershell":
		b.WriteString("# impr completion for PowerShell (generated by impr completion powershell)\n# impr-version: " + version + "\n$imprTable = @{\n")
		for _, c := range sortedKeys(m) {
			quoted := []string{}
			for _, w := range m[c] {
				quoted = append(quoted, "'"+w+"'")
			}
			fmt.Fprintf(&b, "  '%s' = @(%s)\n", c, strings.Join(quoted, ", "))
		}
		quoted := []string{}
		for _, c := range commandNames() {
			quoted = append(quoted, "'"+c+"'")
		}
		fmt.Fprintf(&b, "}\n$imprCommands = @(%s)\n$imprValues = @{\n", strings.Join(quoted, ", "))
		for _, c := range valueCases() {
			vq := []string{}
			for _, v := range strings.Fields(c[1]) {
				vq = append(vq, "'"+v+"'")
			}
			fmt.Fprintf(&b, "  '%s' = @(%s)\n", c[0], strings.Join(vq, ", "))
		}
		b.WriteString("}\n")
		b.WriteString(`Register-ArgumentCompleter -Native -CommandName impr, impr.exe -ScriptBlock {
  param($wordToComplete, $commandAst, $cursorPosition)
  $words = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })
  $prev = if ($wordToComplete -eq '') { $words[-1] } else { $words[-2] }
  if ($words.Count -le 2 -and -not ($words.Count -eq 2 -and $wordToComplete -eq '')) { $cands = $imprCommands }
  elseif ($imprValues.ContainsKey("$($words[1]) $prev")) { $cands = $imprValues["$($words[1]) $prev"] }
  else { $cands = $imprTable[$words[1]] }
  $cands | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
  }
}
`)
	default:
		return "", contract.New(contract.Usage, "%q is not bash, zsh, fish or powershell", shell)
	}
	return b.String(), nil
}

// completionFile is where `impr completion install` puts a shell's script:
// a directory the shell already loads completions from, so no shell profile
// is edited. PowerShell has no such directory, so it is printed instead.
func (a *App) completionFile(shell string) (string, string) {
	switch shell {
	case "bash":
		dir := filepath.Join(a.Home, ".local", "share", "bash-completion", "completions")
		if v := a.Getenv("XDG_DATA_HOME"); filepath.IsAbs(v) {
			dir = filepath.Join(v, "bash-completion", "completions")
		}
		return filepath.Join(dir, "impr"), "bash-completion loads it in new shells"
	case "zsh":
		return filepath.Join(a.Home, ".zfunc", "_impr"), "add once to ~/.zshrc, before compinit: fpath=(~/.zfunc $fpath)"
	case "fish":
		return filepath.Join(a.Home, ".config", "fish", "completions", "impr.fish"), "fish loads it in new shells"
	}
	return "", ""
}

