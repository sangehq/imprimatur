// completionModel reads the usage text, the one list of commands and options,
// into command -> the subcommands and options it takes. Completion is
// generated from it, so it cannot drift from what impr accepts.
func completionModel() map[string][]string {
	words := map[string]map[string]bool{}
	cmd := ""
	optRe := regexp.MustCompile(`--[a-z][a-z-]*`)
	subRe := regexp.MustCompile(`^[a-z][a-z-]*$`)
	add := func(w string) {
		if cmd != "" && w != "" {
			words[cmd][w] = true
		}
	}
	for _, line := range strings.Split(usageText, "\n") {
		rest, ok := strings.CutPrefix(line, "  impr ")
		switch {
		case ok:
			f := strings.Fields(rest)
			cmd = f[0]
			if words[cmd] == nil {
				words[cmd] = map[string]bool{}
			}
			// The second word, and the first word after each " | ", name
			// subcommands when they are plain words (a|b|c lists several).
			segments := strings.Split(strings.Join(f[1:], " "), " | ")
			for _, seg := range segments {
				sf := strings.Fields(seg)
				if len(sf) == 0 {
					continue
				}
				for _, s := range strings.Split(sf[0], "|") {
					if subRe.MatchString(s) {
						add(s)
					}
				}
			}
		case strings.HasPrefix(line, "            ") && cmd != "":
			// a continuation of the command above
		default:
			cmd = ""
			continue
		}
		for _, o := range optRe.FindAllString(line, -1) {
			add(o)
		}
	}
	out := map[string][]string{}
	for c, ws := range words {
		list := []string{}
		for w := range ws {
			list = append(list, w)
		}
		sort.Strings(list)
		out[c] = list
	}
	out["help"] = commandNames()
	// An alias completes like the command it stands for: impr s --pro<TAB>.
	for a, full := range aliases {
		out[a] = out[full]
	}
	return out
}

// commandNames are the top-level commands, from the dispatch table.
func commandNames() []string {
	names := []string{"help", "version"}
	for n := range commands {
		names = append(names, n)
	}
	sort.Strings(names)
	return names
}

func sortedKeys(m map[string][]string) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

// CompletionScript renders the completion for one shell.
func CompletionScript(shell string) (string, error) {
	m := completionModel()
	cmds := strings.Join(commandNames(), " ")
	var b strings.Builder
	switch shell {
	case "bash":
		b.WriteString("# impr completion for bash (generated by impr completion bash)\n_impr() {\n  local cur=${COMP_WORDS[COMP_CWORD]}\n")
		fmt.Fprintf(&b, "  if [ \"$COMP_CWORD\" -eq 1 ]; then COMPREPLY=($(compgen -W %q -- \"$cur\")); return; fi\n  case ${COMP_WORDS[1]} in\n", cmds)
		for _, c := range sortedKeys(m) {
			fmt.Fprintf(&b, "    %s) COMPREPLY=($(compgen -W %q -- \"$cur\"));;\n", c, strings.Join(m[c], " "))
		}
		b.WriteString("  esac\n}\ncomplete -o default -F _impr impr\n")
	case "zsh":
		b.WriteString("#compdef impr\n# impr completion for zsh (generated by impr completion zsh)\n_impr() {\n")
		fmt.Fprintf(&b, "  if (( CURRENT == 2 )); then compadd -- %s; return; fi\n  case $words[2] in\n", cmds)
		for _, c := range sortedKeys(m) {
			fmt.Fprintf(&b, "    %s) compadd -- %s;;\n", c, strings.Join(m[c], " "))
		}
		b.WriteString("  esac\n  _files\n}\n_impr \"$@\"\n")
	case "fish":
		b.WriteString("# impr completion for fish (generated by impr completion fish)\ncomplete -c impr -f\n")
		fmt.Fprintf(&b, "complete -c impr -n __fish_use_subcommand -a %q\n", cmds)
		for _, c := range sortedKeys(m) {
			fmt.Fprintf(&b, "complete -c impr -n '__fish_seen_subcommand_from %s' -a %q\n", c, strings.Join(m[c], " "))
		}
	case "powershell":
		b.WriteString("# impr completion for PowerShell (generated by impr completion powershell)\n$imprTable = @{\n")
		for _, c := range sortedKeys(m) {
			quoted := []string{}
			for _, w := range m[c] {
				quoted = append(quoted, "'"+w+"'")
			}
			fmt.Fprintf(&b, "  '%s' = @(%s)\n", c, strings.Join(quoted, ", "))
		}
		quoted := []string{}
		for _, c := range commandNames() {
			quoted = append(quoted, "'"+c+"'")
		}
		fmt.Fprintf(&b, "}\n$imprCommands = @(%s)\n", strings.Join(quoted, ", "))
		b.WriteString(`Register-ArgumentCompleter -Native -CommandName impr, impr.exe -ScriptBlock {
  param($wordToComplete, $commandAst, $cursorPosition)
  $words = @($commandAst.CommandElements | ForEach-Object { $_.ToString() })
  if ($words.Count -le 2 -and -not ($words.Count -eq 2 -and $wordToComplete -eq '')) { $cands = $imprCommands } else { $cands = $imprTable[$words[1]] }
  $cands | Where-Object { $_ -like "$wordToComplete*" } | ForEach-Object {
    [System.Management.Automation.CompletionResult]::new($_, $_, 'ParameterValue', $_)
  }
}
`)
	default:
		return "", contract.New(contract.Usage, "%q is not bash, zsh, fish or powershell", shell)
	}
	return b.String(), nil
}

// completionFile is where `impr completion install` puts a shell's script:
// a directory the shell already loads completions from, so no shell profile
// is edited. PowerShell has no such directory, so it is printed instead.
func (a *App) completionFile(shell string) (string, string) {
	switch shell {
	case "bash":
		dir := filepath.Join(a.Home, ".local", "share", "bash-completion", "completions")
		if v := a.Getenv("XDG_DATA_HOME"); filepath.IsAbs(v) {
			dir = filepath.Join(v, "bash-completion", "completions")
		}
		return filepath.Join(dir, "impr"), "bash-completion loads it in new shells"
	case "zsh":
		return filepath.Join(a.Home, ".zfunc", "_impr"), "add once to ~/.zshrc, before compinit: fpath=(~/.zfunc $fpath)"
	case "fish":
		return filepath.Join(a.Home, ".config", "fish", "completions", "impr.fish"), "fish loads it in new shells"
	}
	return "", ""
}

var completionFlags = flagSpec{"json": boolFlag}

func cmdCompletion(_ context.Context, a *App, args []string) (int, error) {
	p, err := parse(args, completionFlags)
	if err != nil {
		return 0, err
	}
	if len(p.pos) == 0 {
		return 0, contract.New(contract.Usage, "impr completion bash|zsh|fish|powershell | install SHELL | uninstall SHELL")
	}
	switch p.pos[0] {
	case "install", "uninstall":
		if len(p.pos) != 2 {
			return 0, contract.New(contract.Usage, "impr completion %s bash|zsh|fish", p.pos[0])
		}
		shell := p.pos[1]
		path, note := a.completionFile(shell)
		if path == "" {
			return 0, contract.New(contract.Usage, "%s has no completion folder impr can use; add this to your PowerShell profile: impr completion powershell | Out-String | Invoke-Expression", shell)
		}
		if p.pos[0] == "uninstall" {
			if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
				return 0, err
			}
			a.say("completion removed %s", path)
			return 0, nil
		}
		script, err := CompletionScript(shell)
		if err != nil {
			return 0, err
		}
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //nolint:gosec // G301: a completion folder the shell reads
			return 0, err
		}
		if err := os.WriteFile(path, []byte(script), 0o644); err != nil { //nolint:gosec // G306: a completion script the shell reads
			return 0, err
		}
		a.say("completion wrote %s; %s", path, note)
		return 0, nil
	}
	if len(p.pos) > 1 {
		return 0, contract.New(contract.Usage, "one shell at a time (got %s)", strings.Join(p.pos, " "))
	}
	shell := p.pos[0]
	if shell == "pwsh" { // PowerShell 7's name, as the PowerShell toolkit took it
		shell = "powershell"
	}
	script, err := CompletionScript(shell)
	if err != nil {
		return 0, err
	}
	_, _ = fmt.Fprint(a.Stdout, script)
	return 0, nil
}
