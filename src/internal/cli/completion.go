// completionShells are the shells an install or uninstall names: several,
// all (bash, zsh and fish), or none for the shell in $SHELL (ID-17).
func (a *App) completionShells(verb string, words []string) ([]string, error) {
	if len(words) == 0 {
		sh := filepath.Base(a.Getenv("SHELL"))
		if p, _ := a.completionFile(sh); p == "" {
			return nil, contract.New(contract.Usage, "$SHELL is %q, which impr cannot %s completion for; name the shell", a.Getenv("SHELL"), verb).
				WithFix("impr completion " + verb + " bash|zsh|fish|all")
		}
		return []string{sh}, nil
	}
	if len(words) == 1 && words[0] == "all" {
		return []string{"bash", "zsh", "fish"}, nil
	}
	// Every shell is checked before any file is written.
	for _, w := range words {
		if p, _ := a.completionFile(w); p == "" {
			return nil, contract.New(contract.Usage, "%s has no completion folder impr can use (bash, zsh, fish or all); for PowerShell add this to your profile: impr completion powershell | Out-String | Invoke-Expression", w)
		}
	}
	return words, nil
}

// completionOwned reports what is at a shell's completion path: nothing,
// impr's own generated script (a regular file whose header impr writes), or
// something else, which impr never replaces or removes (security review).
func completionOwned(path, shell string) (exists, owned bool) {
	st, err := os.Lstat(path)
	if err != nil {
		return false, false
	}
	if !st.Mode().IsRegular() {
		return true, false
	}
	f, err := os.Open(path) //nolint:gosec // G304: a shell's completion path under the home folder
	if err != nil {
		return true, false
	}
	defer func() { _ = f.Close() }()
	head := make([]byte, 512)
	n, _ := io.ReadFull(f, head)
	return true, strings.Contains(string(head[:n]), "(generated by impr completion "+shell+")")
}

// completionFileDo installs or removes one shell's completion file. A file
// at the path that impr did not write is left alone, either way.
func (a *App) completionFileDo(verb, shell string) error {
	path, note := a.completionFile(shell)
	if path == "" {
		return contract.New(contract.Usage, "%s has no completion folder impr can use; add this to your PowerShell profile: impr completion powershell | Out-String | Invoke-Expression", shell)
	}
	if exists, owned := completionOwned(path, shell); exists && !owned {
		return contract.New(contract.Usage, "%s was not written by impr (or is a link); impr leaves it alone", path).
			WithFix("move it aside, then: impr completion " + verb + " " + shell)
	}
	if verb == "uninstall" {
		if err := os.Remove(path); err != nil && !os.IsNotExist(err) {
			return err
		}
		a.say("completion removed %s", path)
		return nil
	}
	script, err := CompletionScript(shell)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil { //nolint:gosec // G301: a completion folder the shell reads
		return err
	}
	if err := os.WriteFile(path, []byte(script), 0o644); err != nil { //nolint:gosec // G306: a completion script the shell reads
		return err
	}
	a.say("completion wrote %s; %s", path, note)
	return nil
}

// refreshCompletion rewrites each completion script impr installed when its
// version stamp is older than this impr, quietly and once: after an upgrade
// the installed one offers the old commands and values, and the PowerShell
// line regenerated its cache on a version change (O-97). It never writes from
// a dev build or to downgrade, so most commands only read 512 bytes of each
// script. A file impr did not write is never touched.
func (a *App) refreshCompletion() {
	if a.Home == "" {
		return
	}
	if _, ok := parseVersion(version); !ok {
		return
	}
	for _, sh := range []string{"bash", "zsh", "fish"} {
		f, _ := a.completionFile(sh)
		stamp, owned := completionStamp(f, sh)
		if !owned {
			continue
		}
		// A script from before the stamp was written by an older impr.
		if stamp != "" {
			if c, ok := compareVersions(version, stamp); ok && c <= 0 {
				continue
			}
		}
		want, err := CompletionScript(sh)
		if err != nil {
			continue
		}
		_ = os.WriteFile(f, []byte(want), 0o644) //nolint:gosec // G306: a completion script the shell reads
	}
}

// completionStamp reads the "# impr-version:" line from the header of an
// impr-written completion script; owned is false for anything else.
func completionStamp(path, shell string) (stamp string, owned bool) {
	exists, owned := completionOwned(path, shell)
	if !exists || !owned {
		return "", false
	}
	f, err := os.Open(path) //nolint:gosec // G304: impr's own completion script under the home folder
	if err != nil {
		return "", false
	}
	defer func() { _ = f.Close() }()
	head := make([]byte, 512)
	n, _ := io.ReadFull(f, head)
	for _, l := range strings.Split(string(head[:n]), "\n") {
		if v, ok := strings.CutPrefix(l, "# impr-version: "); ok {
			return strings.TrimSpace(v), true
		}
	}
	return "", true
}

func cmdCompletion(_ context.Context, a *App, args []string) (int, error) {
	p, err := parse(args, completionFlags)
	if err != nil {
		return 0, err
	}
	if len(p.pos) == 0 {
		return 0, contract.New(contract.Usage, "impr completion bash|zsh|fish|powershell | install SHELL | uninstall SHELL")
	}
	switch p.pos[0] {
	case "install", "uninstall":
		shells, err := a.completionShells(p.pos[0], p.pos[1:])
		if err != nil {
			return 0, err
		}
		// A file impr did not write stops the run before any file changes.
		for _, shell := range shells {
			if path, _ := a.completionFile(shell); path != "" {
				if exists, owned := completionOwned(path, shell); exists && !owned {
					return 0, contract.New(contract.Usage, "%s was not written by impr (or is a link); impr leaves it alone, and changed nothing", path).
						WithFix("move it aside, then: impr completion " + p.pos[0] + " " + shell)
				}
			}
		}
		for _, shell := range shells {
			if err := a.completionFileDo(p.pos[0], shell); err != nil {
				return 0, err
			}
		}
		return 0, nil
	}
	if len(p.pos) > 1 {
		return 0, contract.New(contract.Usage, "one shell at a time (got %s)", strings.Join(p.pos, " "))
	}
	shell := p.pos[0]
	if shell == "pwsh" { // PowerShell 7's name, as the PowerShell toolkit took it
		shell = "powershell"
	}
	script, err := CompletionScript(shell)
	if err != nil {
		return 0, err
	}
	_, _ = fmt.Fprint(a.Stdout, script)
	return 0, nil
}

// compareVersions compares two SemVer 2.0.0 versions (a leading v and build
// metadata ignored), reporting false when either is not one, such as "dev".
func compareVersions(a, b string) (int, bool) {
	pa, ok := parseVersion(a)
	if !ok {
		return 0, false
	}
	pb, ok := parseVersion(b)
	if !ok {
		return 0, false
	}
	for i := range 3 {
		if c := cmpInt(pa.core[i], pb.core[i]); c != 0 {
			return c, true
		}
	}
	switch {
	case len(pa.pre) == 0 && len(pb.pre) == 0:
		return 0, true
	case len(pa.pre) == 0:
		return 1, true
	case len(pb.pre) == 0:
		return -1, true
	}
	for i := 0; i < len(pa.pre) && i < len(pb.pre); i++ {
		x, y := pa.pre[i], pb.pre[i]
		xn, xerr := strconv.Atoi(x)
		yn, yerr := strconv.Atoi(y)
		var c int
		switch {
		case xerr == nil && yerr == nil:
			c = cmpInt(xn, yn)
		case xerr == nil:
			c = -1
		case yerr == nil:
			c = 1
		default:
			c = strings.Compare(x, y)
		}
		if c != 0 {
			return c, true
		}
	}
	return cmpInt(len(pa.pre), len(pb.pre)), true
}

type semVersion struct {
	core [3]int
	pre  []string
}

func parseVersion(v string) (semVersion, bool) {
	v = strings.TrimPrefix(v, "v")
	v, _, _ = strings.Cut(v, "+")
	core, pre, hasPre := strings.Cut(v, "-")
	parts := strings.Split(core, ".")
	if len(parts) != 3 {
		return semVersion{}, false
	}
	var out semVersion
	for i, p := range parts {
		n, err := strconv.Atoi(p)
		if err != nil || n < 0 || (len(p) > 1 && p[0] == '0') || strings.ContainsAny(p, "+-") {
			return semVersion{}, false
		}
		out.core[i] = n
	}
	if hasPre {
		if pre == "" {
			return semVersion{}, false
		}
		out.pre = strings.Split(pre, ".")
	}
	return out, true
}

func cmpInt(a, b int) int {
	switch {
	case a > b:
		return 1
	case a < b:
		return -1
	}
	return 0
}
